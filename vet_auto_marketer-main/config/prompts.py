# Emergency keyword detector (used for urgent message detection)
# -------------------------------------------------------------------
EMERGENCY_KEYWORDS_AR = [
    "نزيف", "ينزف", "دم", "تشنج", "تشنجات", "ميصير يتنفس", "ما يتنفس",
    "اختناق", "سم", "مسموم", "حادث", "داس عليه", "ضربة", "طارئ",
    "طوارئ", "يموت", "ميتحرك", "اغمى", "غيبوبة",
]
EMERGENCY_KEYWORDS_EN = [
    "bleeding", "seizure", "not breathing", "choking", "poisoned",
    "accident", "emergency", "dying", "unconscious",
]


def is_emergency(text: str) -> bool:
    if not text:
        return False
    t = text.lower()
    return (
        any(k in t for k in EMERGENCY_KEYWORDS_AR)
        or any(k in t for k in EMERGENCY_KEYWORDS_EN)
    )


